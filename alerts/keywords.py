"""
Детектор фраз о суициде/самоповреждении. Чувствительность важнее специфичности:
лишний сигнал врач отклонит, пропущенный — недопустим. Отрицания («не думаю о суициде»)
намеренно НЕ подавляются, но помечаются, чтобы врач видел контекст.
"""
import re

PATTERNS = [
    r"суицид\w*", r"самоубийств\w*", r"поконч\w*\s+с\s+собой", r"уби(ть|ю)\s+себя",
    r"не\s+хо(чу|чется|телось)(\s+\w+){0,2}\s+жить", r"жить(\s+\w+){0,2}\s+не\s+хо(чу|чется)", r"незачем\s+жить",
    r"хо(чу|чется|телось)(\s+\w+){0,2}\s+умереть", r"лучше\s+(бы\s+)?умереть", r"налож\w*\s+на\s+себя\s+руки",
    r"св(ести|еду|ожу)\s+сч[её]ты\s+с\s+жизнью", r"не\s+хочу\s+просыпаться", r"уйти\s+из\s+жизни",
    r"не\s+вижу\s+(никакого\s+)?смысла\s+(дальше\s+)?жить", r"всё\s+закончить\s+навсегда", r"сделать\s+с\s+собой",
    r"(нет|не\s+вижу)\s+смысла\s+жить", r"лучше\s+бы\s+(меня\s+не\s+было|я\s+умер\w*)",
    r"хочу\s+умереть", r"умереть\s+хочу", r"повеш\w+", r"вскры\w*\s+вен\w*",
    r"выпить\s+все\s+таблетки", r"наглота\w*\s+таблет\w*", r"прыгн\w*\s+с\s+(крыши|моста|балкона)",
    r"режу\s+себя", r"порезал\w*\s+(себя|руки)", r"самоповрежд\w*", r"исчезнуть\s+навсегда",
]
_RX = re.compile("|".join(f"(?:{p})" for p in PATTERNS), re.IGNORECASE)
_NEG = re.compile(r"\bне\s+(думаю|собираюсь|планирую|буду)\b[^.!?]{0,40}$", re.IGNORECASE)


def scan(text: str) -> dict:
    if not text:
        return {"hit": False, "matches": [], "negated": False}
    text = text.replace("ё", "е")
    matches = [m.group(0) for m in _RX.finditer(text)]
    negated = bool(matches) and all(_NEG.search(text[: m.start()]) for m in _RX.finditer(text))
    return {"hit": bool(matches), "matches": matches, "negated": negated}
